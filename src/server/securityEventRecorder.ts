import { randomUUID } from 'node:crypto';
import type { SecurityEventRecord } from './db';
import type { PracticeRpcClient } from './taxguard/practice/practiceStore';
import type { RequestHandler } from 'express';
import type { AuthenticatedRequest } from './auth';

const CODES: Record<string, string> = {
  INVALID_CREDENTIALS: 'AUTH_FAILURE', LOGIN_ATTEMPT_DURING_LOCKOUT: 'AUTH_LOCKOUT', BRUTE_FORCE_LOCKOUT_TRIGGERED: 'AUTH_LOCKOUT',
  DISABLED_USER_LOGIN_ATTEMPT: 'AUTH_FAILURE', PASSWORD_RESET_THROTTLED: 'AUTH_LOCKOUT',
  MFA_CODE_INVALID: 'MFA_DENIAL', MFA_CODE_REPLAY_REJECTED: 'MFA_DENIAL', MFA_VERIFICATION_UNAVAILABLE: 'MFA_DENIAL', STAFF_MFA_REQUIRED: 'MFA_DENIAL',
  CLIENT_RESOURCE_ACCESS_DENIED: 'AUTHORIZATION_DENIAL', RBAC_ACCESS_DENIED: 'AUTHORIZATION_DENIAL', CROSS_TENANT_ACCESS_ATTEMPT: 'AUTHORIZATION_DENIAL',
  CLIENT_ISOLATION_VIOLATION_ATTEMPT: 'AUTHORIZATION_DENIAL', ACCOUNTANT_SCOPE_RESTRICTION: 'AUTHORIZATION_DENIAL',
  RECRUITER_TAX_ACCESS_ATTEMPT: 'AUTHORIZATION_DENIAL', DISABLED_USER_SESSION_BLOCKED: 'AUTHORIZATION_DENIAL',
  MAKER_CHECKER_SELF_APPROVAL_ATTEMPT: 'ADMIN_DENIAL', EXPIRED_SIGNED_URL_ACCESS_ATTEMPT: 'DOCUMENT_DENIAL', MALWARE_SIGNATURE_DETECTED: 'MALWARE_DETECTED',
};
/** Server-generated events only. Outbox mode acknowledges database handoff before delivery;
 * direct mode remains a compatibility path for existing isolated tests. Unacknowledged HTTP
 * finish-hook observations are best-effort. Administrative actions retain transactional audit. */
export class SecurityEventRecorder {
  private tail: Promise<void> = Promise.resolve();
  private pending = 0;
  private persisted = 0;
  private failed = 0;
  private dropped = 0;
  private acknowledged = 0;
  private dispatchFailures = 0;
  private dispatching = false;
  constructor(private readonly client: PracticeRpcClient, private readonly tenant: string, private readonly capacity = 100, private readonly mode: 'direct' | 'outbox' = 'direct') {
    if (!/^[A-Za-z0-9_-]{1,128}$/.test(tenant) || !Number.isInteger(capacity) || capacity < 1 || capacity > 1000) throw new Error('SECURITY_RECORDER_CONFIG_INVALID');
  }
  private args(event: Pick<SecurityEventRecord, 'eventType' | 'userId' | 'severity'>, eventId = randomUUID()) {
    const code = Object.hasOwn(CODES, event.eventType) ? CODES[event.eventType] : undefined;
    if (!code) return null;
    if (!/^[a-f0-9-]{36}$/i.test(eventId)) throw new Error('SECURITY_EVENT_INVALID');
    return { p_tenant: this.tenant, p_actor: event.userId ?? null, p_event: eventId, p_code: code, p_severity: event.severity };
  }
  private async send(args: Record<string, unknown>) {
    const result = await this.client.rpc(this.mode === 'outbox' ? 'taxguard_security_enqueue' : 'taxguard_security_record', args);
    if (result?.error || result?.data?.eventId !== args.p_event || (this.mode === 'outbox' && result.data.acknowledged !== true)) throw new Error('SECURITY_HANDOFF_FAILED');
    if (this.mode === 'outbox') this.acknowledged++; else this.persisted++;
  }
  /** Caller must await this result. Acknowledgment means a committed outbox envelope, not merely
   * an in-memory promise or completed audit delivery. Reuse the server-owned event ID on retry. */
  async recordDurably(event: Pick<SecurityEventRecord, 'eventType' | 'userId' | 'severity'>, eventId = randomUUID()) {
    if (this.mode !== 'outbox') throw new Error('SECURITY_DURABLE_HANDOFF_REQUIRED');
    const args = this.args(event, eventId);
    if (!args) throw new Error('SECURITY_EVENT_INVALID');
    if (this.pending >= this.capacity) { this.dropped++; throw new Error('SECURITY_HANDOFF_BACKPRESSURE'); }
    this.pending++;
    try { await this.send(args); return { eventId, acknowledged: true as const }; }
    catch { this.failed++; throw new Error('SECURITY_HANDOFF_FAILED'); }
    finally { this.pending--; }
  }
  record(event: Pick<SecurityEventRecord, 'eventType' | 'userId' | 'severity'>): void {
    const args = this.args(event);
    if (!args) return;
    if (this.pending >= this.capacity) { this.dropped++; return; }
    // UUID generated by the server; raw details, IP and caller request IDs never enter ingestion.
    this.pending++;
    this.tail = this.tail.then(async () => {
      try {
        await this.send(args);
      } catch { this.failed++; }
      finally { this.pending--; }
    });
  }
  async drain() { await this.tail; }
  async dispatch(limit = 50) {
    if (this.mode !== 'outbox') throw new Error('SECURITY_DURABLE_HANDOFF_REQUIRED');
    if (this.dispatching) return;
    this.dispatching = true;
    try {
      const result = await this.client.rpc('taxguard_security_dispatch', { p_tenant: this.tenant, p_limit: limit });
      if (result?.error || !Number.isInteger(result.data?.delivered) || !Number.isInteger(result.data?.failed) || result.data.delivered < 0 || result.data.failed < 0) throw new Error();
      this.persisted += result.data.delivered;
      this.dispatchFailures += result.data.failed;
    } catch { this.dispatchFailures++; throw new Error('SECURITY_OUTBOX_DISPATCH_FAILED'); }
    finally { this.dispatching = false; }
  }
  status() { return Object.freeze({ pending: this.pending, persisted: this.persisted, failed: this.failed, dropped: this.dropped,
    ...(this.mode === 'outbox' ? { acknowledged: this.acknowledged, dispatchFailures: this.dispatchFailures } : {}) }); }
}

/** Captures transport-level refusals (including provider and invalid-session failures) without
 * reading bodies, headers, query strings or supplied identities. Specific legacy denial events
 * may accompany this refusal; both remain distinguishable bounded server-generated observations. */
export function securityDenialObserver(recorder: SecurityEventRecorder): RequestHandler {
  return (req, res, next) => {
    res.once('finish', () => {
      if (res.statusCode === 401 || res.statusCode === 403) recorder.record({
        eventType: res.statusCode === 401 ? 'INVALID_CREDENTIALS' : 'RBAC_ACCESS_DENIED',
        userId: (req as AuthenticatedRequest).user?.id, severity: 'warning',
      });
    });
    next();
  };
}

import { randomUUID } from 'node:crypto';
import type { SecurityEventRecord } from './db';
import type { PracticeRpcClient } from './taxguard/practice/practiceStore';
import type { RequestHandler } from 'express';
import type { AuthenticatedRequest } from './auth';

const CODES: Record<string, string> = {
  INVALID_CREDENTIALS: 'AUTH_FAILURE', LOGIN_ATTEMPT_DURING_LOCKOUT: 'AUTH_LOCKOUT', BRUTE_FORCE_LOCKOUT_TRIGGERED: 'AUTH_LOCKOUT',
  DISABLED_USER_LOGIN_ATTEMPT: 'AUTH_FAILURE', PASSWORD_RESET_THROTTLED: 'AUTH_LOCKOUT',
  MFA_CODE_INVALID: 'MFA_DENIAL', MFA_CODE_REPLAY_REJECTED: 'MFA_DENIAL', MFA_VERIFICATION_UNAVAILABLE: 'MFA_DENIAL', STAFF_MFA_REQUIRED: 'MFA_DENIAL',
  CLIENT_RESOURCE_ACCESS_DENIED: 'AUTHORIZATION_DENIAL', RBAC_ACCESS_DENIED: 'AUTHORIZATION_DENIAL', CROSS_TENANT_ACCESS_ATTEMPT: 'AUTHORIZATION_DENIAL',
  CLIENT_ISOLATION_VIOLATION_ATTEMPT: 'AUTHORIZATION_DENIAL', ACCOUNTANT_SCOPE_RESTRICTION: 'AUTHORIZATION_DENIAL',
  RECRUITER_TAX_ACCESS_ATTEMPT: 'AUTHORIZATION_DENIAL', DISABLED_USER_SESSION_BLOCKED: 'AUTHORIZATION_DENIAL',
  MAKER_CHECKER_SELF_APPROVAL_ATTEMPT: 'ADMIN_DENIAL', EXPIRED_SIGNED_URL_ACCESS_ATTEMPT: 'DOCUMENT_DENIAL', MALWARE_SIGNATURE_DETECTED: 'MALWARE_DETECTED',
};
/** Bounded bridge for server-generated legacy denials. Existing administrative mutations already
 * record transactional audit rows. Telemetry from browsers is deliberately excluded. Successful
 * ingestion is durable; pending items are volatile and dropped/failure counts must be monitored. */
export class SecurityEventRecorder {
  private tail: Promise<void> = Promise.resolve();
  private pending = 0;
  private persisted = 0;
  private failed = 0;
  private dropped = 0;
  constructor(private readonly client: PracticeRpcClient, private readonly tenant: string, private readonly capacity = 100) {
    if (!/^[A-Za-z0-9_-]{1,128}$/.test(tenant) || !Number.isInteger(capacity) || capacity < 1 || capacity > 1000) throw new Error('SECURITY_RECORDER_CONFIG_INVALID');
  }
  record(event: Pick<SecurityEventRecord, 'eventType' | 'userId' | 'severity'>): void {
    const code = Object.hasOwn(CODES, event.eventType) ? CODES[event.eventType] : undefined;
    if (!code) return;
    if (this.pending >= this.capacity) { this.dropped++; return; }
    // UUID generated by the server; raw details, IP and caller request IDs never enter ingestion.
    const args = { p_tenant: this.tenant, p_actor: event.userId ?? null, p_event: randomUUID(), p_code: code, p_severity: event.severity };
    this.pending++;
    this.tail = this.tail.then(async () => {
      try {
        const result = await this.client.rpc('taxguard_security_record', args);
        if (result?.error || !result?.data || (result.data as any).eventId !== args.p_event) this.failed++;
        else this.persisted++;
      } catch { this.failed++; }
      finally { this.pending--; }
    });
  }
  async drain() { await this.tail; }
  status() { return Object.freeze({ pending: this.pending, persisted: this.persisted, failed: this.failed, dropped: this.dropped }); }
}

/** Captures transport-level refusals (including provider and invalid-session failures) without
 * reading bodies, headers, query strings or supplied identities. Specific legacy denial events
 * may accompany this refusal; both remain distinguishable bounded server-generated observations. */
export function securityDenialObserver(recorder: SecurityEventRecorder): RequestHandler {
  return (req, res, next) => {
    res.once('finish', () => {
      if (res.statusCode === 401 || res.statusCode === 403) recorder.record({
        eventType: res.statusCode === 401 ? 'INVALID_CREDENTIALS' : 'RBAC_ACCESS_DENIED',
        userId: (req as AuthenticatedRequest).user?.id, severity: 'warning',
      });
    });
    next();
  };
}

// Pre-validation review for NOT VALID constraints (Phase 14, Block 15).
//
// NOT VALID constraints are enforced for new and updated rows but have never been checked against
// historical rows. Before an owner runs `ALTER TABLE ... VALIDATE CONSTRAINT` on any hosted database,
// each constraint needs a read-only count of the rows that would fail. This module turns the catalog
// definition (pg_get_constraintdef) into that count query. It never validates, alters or repairs.

const IDENT = /^[a-z_][a-z0-9_]*$/;
const quoteIdent = name => {
  if (!IDENT.test(name)) throw new Error('NOT_VALID_REVIEW_IDENTIFIER_REFUSED');
  return `"${name}"`;
};
const qualified = table => {
  const [schema, relation] = table.includes('.') ? table.split('.') : ['public', table];
  return `${quoteIdent(schema)}.${quoteIdent(relation)}`;
};
const columns = list => list.split(',').map(c => quoteIdent(c.trim()));

/**
 * @param {{ table: string; name: string; definition: string; type: 'c' | 'f' }} constraint
 *   table: schema-qualified relation; definition: pg_get_constraintdef output.
 * @returns {string} SELECT returning one row with `violations` (bigint).
 */
export function violationQuery(constraint) {
  const table = qualified(constraint.table);
  if (constraint.type === 'c') {
    const m = /^CHECK \(([\s\S]*)\)(?: NOT VALID)?$/.exec(constraint.definition.trim());
    if (!m) throw new Error('NOT_VALID_REVIEW_UNSUPPORTED_CHECK');
    // A CHECK passes when its expression is true or NULL, so only FALSE is a violation.
    return `SELECT count(*)::bigint AS violations FROM ${table} WHERE (${m[1]}) IS FALSE`;
  }
  if (constraint.type === 'f') {
    const m = /^FOREIGN KEY \(([^)]+)\) REFERENCES ([\w.]+)\(([^)]+)\)/.exec(constraint.definition.trim());
    if (!m) throw new Error('NOT_VALID_REVIEW_UNSUPPORTED_FOREIGN_KEY');
    const local = columns(m[1]), remote = columns(m[3]);
    if (local.length !== remote.length) throw new Error('NOT_VALID_REVIEW_UNSUPPORTED_FOREIGN_KEY');
    // MATCH SIMPLE: a row with any NULL key column is not checked.
    const present = local.map(c => `child.${c} IS NOT NULL`).join(' AND ');
    const join = local.map((c, i) => `parent.${remote[i]} = child.${c}`).join(' AND ');
    return `SELECT count(*)::bigint AS violations FROM ${table} AS child WHERE ${present} AND NOT EXISTS (SELECT 1 FROM ${qualified(m[2])} AS parent WHERE ${join})`;
  }
  throw new Error('NOT_VALID_REVIEW_UNSUPPORTED_TYPE');
}

/** Catalog query for every unvalidated constraint in the public schema. */
export const UNVALIDATED_CONSTRAINTS_SQL = `SELECT c.conrelid::regclass::text AS table, c.conname AS name, c.contype AS type,
  pg_get_constraintdef(c.oid) AS definition FROM pg_constraint c
  WHERE c.connamespace = 'public'::regnamespace AND NOT c.convalidated ORDER BY 1, 2`;

/** Markdown review sheet; the owner records counts and approvals outside the repository. */
export function reviewDocument(constraints) {
  const rows = constraints.map((c, i) => {
    const table = c.table.includes('.') ? c.table : `public.${c.table}`;
    return [`### ${i + 1}. \`${c.name}\` on \`${table}\``, '',
      `Definition: \`${c.definition}\``, '',
      'Read-only violation count (expected `0` before validation):', '', '```sql', violationQuery({ ...c, table }) + ';', '```', '',
      'If the count is not zero, the rows must be corrected through a reviewed, audited data change approved by the data owner;',
      'they must not be deleted or edited ad hoc. Only after a zero count on the target database, and with written owner approval,',
      'may an authorized operator run:', '', '```sql', `ALTER TABLE ${qualified(table)} VALIDATE CONSTRAINT ${quoteIdent(c.name)};`, '```', ''].join('\n');
  });
  return ['# NOT VALID constraint review', '',
    'Generated by `npm run staging:not-valid:review` from a disposable loopback PostgreSQL composition of the canonical',
    'migration plan. **Nothing here has been run against any hosted database.** NOT VALID constraints already reject new',
    'and updated rows; validation only proves that historical rows also comply.', '',
    'Approval steps for each constraint: (1) run the read-only count on the isolated staging copy; (2) record the count and',
    'any remediation plan; (3) obtain written approval from the data owner; (4) validate during an approved maintenance',
    'window (VALIDATE CONSTRAINT takes a SHARE UPDATE EXCLUSIVE lock on the table and a ROW SHARE lock on a referenced table);',
    '(5) re-run the count and record the result. Production follows only after staging acceptance.', '',
    `Unvalidated constraints in the composed schema: **${constraints.length}**.`, '', ...rows].join('\n').replace(/\n+$/, '');
}

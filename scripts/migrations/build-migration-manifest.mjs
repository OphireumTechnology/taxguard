// Writes the canonical migration execution manifest (Markdown and JSON) from the offline audit.
// Usage: node scripts/migrations/build-migration-manifest.mjs [--check]
// --check exits 1 when the committed manifest differs from a fresh audit (no files written).
// Offline only: PGlite in process; no environment credentials are read and nothing is connected.
import fs from 'node:fs';
import { auditMigrations } from './migration-audit.mjs';

export const MANIFEST_JSON = 'docs/development/migration-execution-manifest.json';
export const MANIFEST_MD = 'docs/development/migration-execution-manifest.md';

const short = f => f.split('/').pop().replace(/\.sql$/, '');
const fnName = s => s.slice(0, s.indexOf('('));

export async function buildManifest(root = '.') {
  const supabase = await auditMigrations(root, { supabaseDefaults: true });
  const plain = await auditMigrations(root, { supabaseDefaults: false });
  const files = supabase.files.map((f, i) => ({
    order: f.order, kind: f.kind, file: f.file, appliesInOrder: f.applied && plain.files[i].applied, reapply: f.reapply,
    tablesAdded: f.tablesAdded, functionsAdded: f.functionsAdded.map(fnName), supersedes: f.supersedes.map(s => ({ function: fnName(s.fn), previous: s.originallyDefinedIn })),
    functionsRemoved: f.functionsRemoved.map(fnName), policiesAdded: f.policiesAdded, triggersAdded: f.triggersAdded.length, indexesAdded: f.indexesAdded.length,
    notValidConstraints: f.notValidConstraints, prerequisites: f.prerequisites.map(p => supabase.files.find(x => x.file === p).order),
    clientRoleAccess: f.clientGrants.map(g => ({ object: g.object.startsWith('fn:') ? 'function ' + fnName(g.object.slice(3)) : 'table ' + g.object.slice(6), write: g.write })),
    serviceRoleRevoked: plain.files[i].serviceRevoked.map(fnName),
    definerWithoutSearchPath: f.definerWithoutPath.map(fnName), tablesWithoutRls: f.tablesWithoutRls, hazards: f.hazards.map(h => h.code),
  }));
  return { generatedBy: 'scripts/migrations/build-migration-manifest.mjs', order: 'explicit dependency DAG; separate audit draft analyzed last and excluded from execution authority',
    summary: { files: files.length, core: supabase.summary.core, proposals: supabase.summary.proposals, tables: supabase.summary.tables, functions: supabase.summary.functions,
      securityDefinerFunctions: supabase.summary.definerFns,
      clientExecutableFunctionsWithSupabaseDefaults: supabase.summary.clientExecutable.map(fnName), clientExecutableFunctionsWithoutDefaults: plain.summary.clientExecutable.map(fnName),
      clientReachableTablesWithSupabaseDefaults: supabase.summary.clientTables },
    files };
}

export function renderMarkdown(m) {
  const cell = v => (Array.isArray(v) ? v.join(', ') : String(v ?? '')).replace(/\|/g, '\\|') || '—';
  const lines = [
    '# Migration catalog audit (derived from canonical dependency plan)',
    '',
    '> Generated by `node scripts/migrations/build-migration-manifest.mjs` from an offline audit (PGlite, empty synthetic schema).',
    '> Do not edit by hand; `src/tests/migrationReadinessAudit.test.ts` fails when this file is stale.',
    '> Nothing here has been applied to any Supabase project. Every proposal still needs human review and approval.',
    '',
    `Execution order: ${m.order}. ${m.summary.files} files (${m.summary.core} core, ${m.summary.proposals} proposals, 1 separate audit proposal);`,
    `${m.summary.tables} tables and ${m.summary.functions} public functions (${m.summary.securityDefinerFunctions} SECURITY DEFINER) after composition.`,
    '',
    `Functions executable by anon or authenticated after every file, with Supabase default privileges: ${cell(m.summary.clientExecutableFunctionsWithSupabaseDefaults)};`,
    `without default privileges: ${cell(m.summary.clientExecutableFunctionsWithoutDefaults)}.`,
    `Tables reachable by anon or authenticated after every file, with Supabase default privileges: ${cell(m.summary.clientReachableTablesWithSupabaseDefaults.map(t => t.table + (t.anon ? ' (anon)' : '') + (t.authenticatedWrite ? ' (write)' : ' (read)')))}.`,
    '',
    '| # | File | Kind | Re-apply | +Tables | +Functions | Supersedes | Prerequisites (#) | NOT VALID | Client-role access added | Hazards |',
    '|---|---|---|---|---|---|---|---|---|---|---|',
    ...m.files.map(f => `| ${f.order} | \`${short(f.file)}\` | ${f.kind} | ${f.reapply === 'ok' ? 'ok' : 'not re-runnable'} | ${f.tablesAdded.length} | ${f.functionsAdded.length} | ${cell(f.supersedes.map(s => s.function + ' (from #' + (m.files.find(x => x.file === s.previous)?.order ?? '?') + ')'))} | ${cell(f.prerequisites)} | ${f.notValidConstraints.length} | ${cell(f.clientRoleAccess.map(a => a.object + (a.write ? ' (write)' : '')).slice(0, 3).concat(f.clientRoleAccess.length > 3 ? ['… ' + f.clientRoleAccess.length + ' objects'] : []))} | ${cell(f.hazards)} |`),
    '',
    '## Not re-runnable files',
    '',
    ...m.files.filter(f => f.reapply !== 'ok').map(f => `- #${f.order} \`${short(f.file)}\`: ${f.reapply.replace(/^fails: /, '')}`),
    '',
    '## Constraints added NOT VALID (validate after data review)',
    '',
    ...m.files.filter(f => f.notValidConstraints.length).map(f => `- #${f.order} \`${short(f.file)}\`: ${f.notValidConstraints.join(', ')}`),
    '',
    '## Functions whose service-role execution depended only on PUBLIC (no default privileges)',
    '',
    ...m.files.filter(f => f.serviceRoleRevoked.length).map(f => `- #${f.order} \`${short(f.file)}\` revokes: ${f.serviceRoleRevoked.join(', ')}`),
    '',
  ];
  return lines.join('\n');
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/').replace(/^([A-Za-z]):/, '/$1:')}` || process.argv[1]?.endsWith('build-migration-manifest.mjs')) {
  const m = await buildManifest('.');
  const json = JSON.stringify(m, null, 2) + '\n', md = renderMarkdown(m);
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(MANIFEST_JSON) && fs.readFileSync(MANIFEST_JSON, 'utf8').replace(/\r\n/g,'\n') === json && fs.existsSync(MANIFEST_MD) && fs.readFileSync(MANIFEST_MD, 'utf8').replace(/\r\n/g,'\n') === md;
    console.log(same ? 'MANIFEST_CURRENT' : 'MANIFEST_STALE');
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(MANIFEST_JSON, json); fs.writeFileSync(MANIFEST_MD, md);
  console.log(`MANIFEST_WRITTEN files=${m.summary.files}`);
}

#!/usr/bin/env node
/**
 * Provision the LOCAL TaxGuard super administrator (non-production only).
 *
 *   node scripts/provision-super-admin.mjs [--out .env.superadmin.local] [--force]
 *
 * Prompts for the e-mail, tenant and password (password input is hidden and never echoed),
 * derives the pbkdf2 hash used by src/server/auth.ts, generates a 160-bit TOTP secret and
 * writes the TAXGUARD_SUPER_ADMIN_* variables to a git-ignored env file. The plaintext
 * password is never written anywhere. Enrol the printed otpauth URI (or the secret) in an
 * authenticator app, then start the server with:
 *
 *   npx tsx --env-file=.env.superadmin.local server.ts
 *
 * This script does not contact Supabase, any network service or any production system.
 */
import { pbkdf2Sync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import readline from 'node:readline';

const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const outPath = resolve(outIndex >= 0 ? args[outIndex + 1] : '.env.superadmin.local');
const force = args.includes('--force');

// Must match src/server/auth.ts (hashPassword / verifyPassword).
const SALT_LENGTH = 16, KEY_LENGTH = 64, ITERATIONS = 10000, DIGEST = 'sha512';
const BASE32 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';

function base32Encode(buf) {
  let bits = 0, value = 0, out = '';
  for (const byte of buf) {
    value = (value << 8) | byte; bits += 8;
    while (bits >= 5) { out += BASE32[(value >>> (bits - 5)) & 31]; bits -= 5; }
  }
  if (bits > 0) out += BASE32[(value << (5 - bits)) & 31];
  return out;
}

function ask(question) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise(res => rl.question(question, answer => { rl.close(); res(answer.trim()); }));
}

function askHidden(question) {
  return new Promise((res, rej) => {
    const stdin = process.stdin;
    if (!stdin.isTTY) return rej(new Error('Run this script in an interactive terminal (password input must be hidden).'));
    process.stdout.write(question);
    stdin.setRawMode(true); stdin.resume(); stdin.setEncoding('utf8');
    let value = '';
    const onData = ch => {
      if (ch === '\u0003') { stdin.setRawMode(false); process.stdout.write('\n'); process.exit(130); }
      if (ch === '\r' || ch === '\n' || ch === '\u0004') {
        stdin.setRawMode(false); stdin.pause(); stdin.removeListener('data', onData);
        process.stdout.write('\n'); return res(value);
      }
      if (ch === '\u007f' || ch === '\b') { value = value.slice(0, -1); return; }
      value += ch;
    };
    stdin.on('data', onData);
  });
}

function passwordProblems(pw, email) {
  const problems = [];
  if (pw.length < 14) problems.push('at least 14 characters');
  if (!/[a-z]/.test(pw) || !/[A-Z]/.test(pw)) problems.push('upper- and lower-case letters');
  if (!/\d/.test(pw)) problems.push('a digit');
  if (!/[^A-Za-z0-9]/.test(pw)) problems.push('a symbol');
  if (email && pw.toLowerCase().includes(email.split('@')[0].toLowerCase())) problems.push('must not contain the e-mail name');
  return problems;
}

async function main() {
  if (process.env.NODE_ENV === 'production') {
    console.error('Refusing to run with NODE_ENV=production. Production identity is managed in Supabase.');
    process.exit(1);
  }
  if (existsSync(outPath) && !force) {
    console.error(`${outPath} already exists. Re-run with --force to replace it (this resets the password and the authenticator secret).`);
    process.exit(1);
  }

  console.log('TaxGuard local super administrator provisioning (non-production).');
  const email = (await ask('Super administrator e-mail (use a dedicated address): ')).toLowerCase();
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) { console.error('Invalid e-mail address.'); process.exit(1); }
  const tenant = (await ask('Tenant id to administer [tenantA]: ')) || 'tenantA';
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(tenant)) { console.error('Invalid tenant id.'); process.exit(1); }
  const name = (await ask('Display name [Super Administrator]: ')) || 'Super Administrator';

  const password = await askHidden('Password (hidden): ');
  const problems = passwordProblems(password, email);
  if (problems.length) { console.error(`Password rejected; it needs: ${problems.join(', ')}.`); process.exit(1); }
  if ((await askHidden('Confirm password (hidden): ')) !== password) { console.error('Passwords do not match.'); process.exit(1); }

  const salt = randomBytes(SALT_LENGTH).toString('hex');
  const hash = pbkdf2Sync(password, salt, ITERATIONS, KEY_LENGTH, DIGEST).toString('hex');
  const totpSecret = base32Encode(randomBytes(20));
  const safeName = name.replace(/[\r\n"]/g, '');

  const body = [
    '# TaxGuard LOCAL super administrator. Generated by scripts/provision-super-admin.mjs.',
    '# Git-ignored. Never commit, share or use this file in production.',
    `TAXGUARD_SUPER_ADMIN_EMAIL=${email}`,
    `TAXGUARD_SUPER_ADMIN_PASSWORD_HASH=${salt}:${hash}`,
    `TAXGUARD_SUPER_ADMIN_TOTP_SECRET=${totpSecret}`,
    `TAXGUARD_SUPER_ADMIN_TENANT_ID=${tenant}`,
    `TAXGUARD_SUPER_ADMIN_NAME="${safeName}"`,
    ''
  ].join('\n');
  writeFileSync(outPath, body, { encoding: 'utf8', mode: 0o600 });

  const issuer = 'TaxGuard AI (local)';
  const uri = `otpauth://totp/${encodeURIComponent(`${issuer}:${email}`)}?secret=${totpSecret}&issuer=${encodeURIComponent(issuer)}&algorithm=SHA1&digits=6&period=30`;
  console.log(`\nWrote ${outPath} (the password itself was not stored).`);
  console.log('\nAdd this account to your authenticator app now. It is shown only once:');
  console.log(`  Secret (manual entry): ${totpSecret}`);
  console.log(`  otpauth URI:           ${uri}`);
  console.log('\nStart the local server with:');
  console.log(`  npx tsx --env-file=${outIndex >= 0 ? args[outIndex + 1] : '.env.superadmin.local'} server.ts`);
  console.log('Then sign in at http://localhost:3000/staff/login and open /staff/super-admin.');
}

main().catch(err => { console.error(err.message); process.exit(1); });

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = process.cwd();
const output = process.argv.includes('--output') ? process.argv[process.argv.indexOf('--output') + 1] : 'ip-audit-report.json';
const sourceExt = new Set(['.ts','.tsx','.js','.jsx','.mjs','.cjs','.py','.go','.rs','.java','.cs','.php','.html','.css','.scss','.sql','.sh','.yml','.yaml']);
const excluded = /(^|\/)(node_modules|dist|build|coverage|vendor|\.git|\.next|\.turbo|\.output)(\/|$)|(^|\/)\.env($|\.)|(^|\/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock)$/i;
const files = execFileSync('git',['ls-files','-z'],{encoding:'utf8'}).split('\0').filter(Boolean);
const rows = [];
for (const file of files) {
  if (excluded.test(file)) continue;
  if (!sourceExt.has(path.extname(file).toLowerCase())) continue;
  let content = '';
  try { content = fs.readFileSync(path.join(root,file),'utf8'); } catch { continue; }
  const first = content.slice(0,2500);
  const hasCopyright = /copyright|©|SPDX-License-Identifier|@license/i.test(first);
  const hasOphireum = /ophireum|OPH-IP/i.test(first);
  const thirdParty = /SPDX-License-Identifier:\s*(Apache-2\.0|MIT|BSD|GPL|LGPL|MPL|ISC)/i.test(first) && !hasOphireum;
  const generated = /generated file|do not edit|@generated|generated by/i.test(first);
  rows.push({path:file,extension:path.extname(file),bytes:Buffer.byteLength(content),hasCopyrightOrLicenseHeader:hasCopyright,hasOphireumIdentifier:hasOphireum,possibleThirdPartyOrLicenseHeader:thirdParty,possibleGeneratedFile:generated,reviewStatus:'UNVERIFIED'});
}
const summary = {
  generatedAt:new Date().toISOString(),
  repository:process.env.GITHUB_REPOSITORY || 'OphireumTechnology/taxguard',
  commit:process.env.GITHUB_SHA || execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),
  mode:'READ_ONLY_AUDIT_NO_SOURCE_MODIFICATIONS',
  trackedSourceFilesScanned:rows.length,
  alreadyContainingCopyrightOrLicenseHeader:rows.filter(x=>x.hasCopyrightOrLicenseHeader).length,
  containingOphireumIdentifier:rows.filter(x=>x.hasOphireumIdentifier).length,
  possibleThirdPartyOrLicenseHeaders:rows.filter(x=>x.possibleThirdPartyOrLicenseHeader).length,
  possibleGeneratedFiles:rows.filter(x=>x.possibleGeneratedFile).length,
  filesRequiringHumanOwnershipReview:rows.length,
  rows
};
fs.writeFileSync(output,JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify({...summary,rows:undefined},null,2));

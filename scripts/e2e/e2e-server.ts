/**
 * Browser end-to-end test server (development only; run by scripts/e2e/run-e2e.mjs).
 *
 * Boots the real server.ts (real Express routers, real Vite-served React UI, real local
 * password + TOTP sign-in) with:
 *   - a throw-away local PostgreSQL (embedded-postgres, loopback only) holding the core
 *     migrations plus every proposal, seeded with synthetic tenants, clients and members;
 *   - a loopback PostgREST-style RPC endpoint in front of it, so the durable stores reach the
 *     database through the same supabase-js client they use against a real project;
 *   - synthetic staff and client users whose passwords and TOTP secrets were generated by the
 *     runner for this run only (enrolled exactly as a provisioned authenticator would be).
 * It refuses to start in production, beside a .env file, or with any Supabase project in the
 * environment. No production service, credential or data is ever touched.
 */
import fs from 'node:fs';
import {randomUUID} from 'node:crypto';
import http from 'node:http';
import type { AddressInfo } from 'node:net';
import { pgRpc, startDatabase } from '../../src/tests-db/harness';
import { handleProviderEmulation } from './providerEmulator';

if (process.env.NODE_ENV === 'production') throw new Error('E2E server refuses to run in production.');
for (const f of ['.env', '.env.local', '.env.development', '.env.development.local'])
  if (fs.existsSync(f)) throw new Error(`E2E server refuses to run beside ${f}: move it aside so no real project can be loaded.`);
for (const k of ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY', 'VITE_SUPABASE_URL', 'VITE_SUPABASE_ANON_KEY', 'SEED_STAFF_PASSWORD', 'SEED_CLIENT_PASSWORD'])
  if (process.env[k]) throw new Error(`E2E server refuses to run with ${k} set.`);
const credentialsFile = process.env.E2E_CREDENTIALS_FILE;
if (!credentialsFile) throw new Error('E2E_CREDENTIALS_FILE is required.');
type E2EUser = { id: string; email: string; name: string; role: string; tenantId: string; clientId?: string; authorizedClientIds?: string[]; password: string; totp: string };
const { users } = JSON.parse(fs.readFileSync(credentialsFile, 'utf8')) as { users: E2EUser[] };

export const E2E = { tenant: 'tenantE2E', other: 'tenantE2EOther', client: 'e2eClient', otherTenantClient: 'e2eForeignClient', unassignedClient: 'e2eUnassigned' };

const database = await startDatabase();
const q = (sql: string) => database.pool.query(sql);
const members = users.map(u => `('${u.tenantId}','${u.id}','${u.role === 'super_admin' ? 'admin' : u.role}','active',${u.clientId ? `'${u.clientId}'` : 'NULL'})`).join(',');
// Identity rows carry the synthetic name and email: the staff directory fails closed on incomplete identities.
const identityNames = users.map(u => `('${u.id}','${u.email.replace(/'/g, "''")}','${u.name.replace(/'/g, "''")}')`).join(',');
await q(`INSERT INTO taxguard_tenants(id,name) VALUES('${E2E.tenant}','Synthetic E2E Practice'),('${E2E.other}','Synthetic Other Practice');
  INSERT INTO taxguard_clients(tenant_id,client_id,owner_uid,name) VALUES('${E2E.tenant}','${E2E.client}','e2e-client','Synthetic Client One'),
    ('${E2E.tenant}','${E2E.unassignedClient}','e2e-nobody','Synthetic Unassigned Client'),('${E2E.other}','${E2E.otherTenantClient}','e2e-foreign-owner','Synthetic Foreign Client');
  INSERT INTO taxguard_members(tenant_id,uid,role,status,client_id) VALUES ${members};
  INSERT INTO taxguard_identities(tenant_id,uid,user_data) SELECT m.tenant_id,m.uid,jsonb_build_object('id',m.uid,'tenantId',m.tenant_id,'role',m.role,'status',m.status,'email',n.email,'name',n.name)
    FROM taxguard_members m JOIN (VALUES ${identityNames}) AS n(uid,email,name) ON n.uid = m.uid WHERE m.uid LIKE 'e2e-%';
  -- Durable (provider-session) staff for the staff-security suite. Their provider accounts are
  -- created by the tests through /e2e/provider-user; they have no local password.
  INSERT INTO taxguard_members(tenant_id,uid,role,status) VALUES ('${E2E.tenant}','d0000000-0000-4000-8000-00000000000a','admin','active'),('${E2E.tenant}','d0000000-0000-4000-8000-00000000000b','admin','active'),
    ('${E2E.tenant}','d0000000-0000-4000-8000-00000000000c','admin','active'),('${E2E.tenant}','d0000000-0000-4000-8000-000000000001','accountant','active'),('${E2E.tenant}','d0000000-0000-4000-8000-000000000002','accountant','active'),
    -- Phase 13A onboarding status (C4): an active accountant with no assignments, used by no other suite.
    ('${E2E.tenant}','d0000000-0000-4000-8000-000000000003','accountant','active'),
    -- MFA recovery retry / cancellation / self-reactivation (provider suite 09 only).
    ('${E2E.tenant}','d0000000-0000-4000-8000-000000000004','accountant','active'),('${E2E.tenant}','d0000000-0000-4000-8000-000000000005','accountant','active'),
    -- An administrator of ANOTHER tenant (cross-tenant denial): no membership in this deployment's tenant.
    ('${E2E.other}','d0000000-0000-4000-8000-0000000000f1','admin','active');
  INSERT INTO taxguard_identities(tenant_id,uid,user_data) SELECT tenant_id,uid,jsonb_build_object('id',uid,'tenantId',tenant_id,'role',role,'status',status,
    'email',uid||'@example.test','name','Synthetic '||uid,'mfaEnabled',true,'isVerified',true) FROM taxguard_members WHERE uid LIKE 'd0000000-%';
  -- Phase 13B client MFA (C2): a durable client that signs in through the provider emulation.
  INSERT INTO taxguard_clients(tenant_id,client_id,owner_uid,name,email,status) VALUES('${E2E.tenant}','E2EMFAC1','d0000000-0000-4000-8000-0000000000c1','Synthetic Provider Client','d0000000-0000-4000-8000-0000000000c1@example.test','active');
  INSERT INTO taxguard_members(tenant_id,uid,role,status,client_id) VALUES('${E2E.tenant}','d0000000-0000-4000-8000-0000000000c1','client','active','E2EMFAC1');
  INSERT INTO taxguard_identities(tenant_id,uid,user_data) VALUES('${E2E.tenant}','d0000000-0000-4000-8000-0000000000c1',jsonb_build_object('id','d0000000-0000-4000-8000-0000000000c1',
    'tenantId','${E2E.tenant}','role','client','status','active','email','d0000000-0000-4000-8000-0000000000c1@example.test','name','Synthetic Provider Client',
    'clientId','E2EMFAC1','isVerified',true,'onboardingStatus','COMPLETED'));
  INSERT INTO taxguard_clients(tenant_id,client_id,owner_uid,name,email,status) VALUES('${E2E.tenant}','E2EMFAC2','d0000000-0000-4000-8000-0000000000c2','Synthetic Second Client','d0000000-0000-4000-8000-0000000000c2@example.test','active');
  INSERT INTO taxguard_members(tenant_id,uid,role,status,client_id) VALUES('${E2E.tenant}','d0000000-0000-4000-8000-0000000000c2','client','active','E2EMFAC2');
  INSERT INTO taxguard_identities(tenant_id,uid,user_data) VALUES('${E2E.tenant}','d0000000-0000-4000-8000-0000000000c2',jsonb_build_object('id','d0000000-0000-4000-8000-0000000000c2',
    'tenantId','${E2E.tenant}','role','client','status','active','email','d0000000-0000-4000-8000-0000000000c2@example.test','name','Synthetic Second Client',
    'clientId','E2EMFAC2','isVerified',true,'onboardingStatus','COMPLETED'));`);

// Loopback stand-in for the project's service endpoints, keyed per run:
//   POST /rest/v1/rpc/<taxguard_*>        -> the database RPC (PostgREST semantics)
//   GET  /storage/v1/bucket/<vault>       -> a PRIVATE bucket (public: false)
//   POST /storage/v1/object/<vault>/<p>   -> write-once object store held in memory
//   POST /storage/v1/object/sign/<vault>/<p> -> a signed URL on an .invalid host (never fetched)
//   POST /e2e/scan                        -> the external malware scanner's verdict, recorded
//                                            through one-use job/verdict RPCs (fake detection only)
// Everything else is 404, so any unexpected provider call fails closed.
const rpc = pgRpc(database.pool);
const serviceKey = 'e2e-synthetic-service-key-' + Math.random().toString(36).slice(2);
// Provider-mode profile: the browser gets its own (public, per-run) key that only opens the
// browser-facing auth endpoints; database, storage, admin and control paths need the service key.
const PROVIDER_PROFILE = process.env.E2E_PROFILE === 'provider';
const anonKey = 'e2e-synthetic-anon-key-' + Math.random().toString(36).slice(2);
const BROWSER_AUTH = /^\/auth\/v1\/(token|logout|user|factors(\/[0-9a-f-]{36}(\/(challenge|verify))?)?)$/;
const objects = new Map<string, Buffer>();
const shim = http.createServer((req, res) => {
  const cors: Record<string, string> = PROVIDER_PROFILE ? { 'access-control-allow-origin': '*', 'access-control-allow-headers': 'authorization, apikey, content-type, x-client-info, x-supabase-api-version',
    'access-control-allow-methods': 'GET, POST, PUT, PATCH, DELETE, OPTIONS' } : {};
  const send = (status: number, body: unknown) => { res.writeHead(status, { 'content-type': 'application/json', ...cors }); res.end(status === 204 ? '' : JSON.stringify(body)); };
  const path = (req.url || '').split('?')[0];
  if (PROVIDER_PROFILE && req.method === 'OPTIONS' && BROWSER_AUTH.test(path)) { res.writeHead(204, cors); return res.end(); }
  const key = req.headers.apikey || String(req.headers.authorization || '').replace(/^Bearer /, '');
  const browserAllowed = PROVIDER_PROFILE && key === anonKey && BROWSER_AUTH.test(path);
  if (key !== serviceKey && !browserAllowed) return send(401, { code: 'E2E_KEY', message: 'Unknown key', statusCode: '401', error: 'Unauthorized' });
  const chunks: Buffer[] = []; let size = 0;
  req.on('data', (c: Buffer) => { size += c.length; if (size > 30_000_000) req.destroy(); else chunks.push(c); });
  req.on('end', async () => {
    const raw = Buffer.concat(chunks);
    const json = () => { try { return raw.length ? JSON.parse(raw.toString('utf8')) : {}; } catch { return null; } };
    let m: RegExpExecArray | null;
    // Provider and PostgREST-table emulation for the durable identity paths (providerEmulator.ts).
    if (await handleProviderEmulation(req.method || 'GET', new URL(req.url || '/', 'http://127.0.0.1'), req.headers, json() ?? {}, database.pool, send)) return;
    // Runs one MFA reset-worker step now, through the real provider adapter against the emulation.
    if (req.method === 'POST' && path === '/e2e/run-reset-worker') {
      const { runMfaResetJob } = await import('../../src/server/mfaRecoveryCompletion');
      const { configuredMfaResetProvider } = await import('../../src/server/mfaResetProvider');
      const { getSupabaseAdmin } = await import('../../src/server/supabase');
      try { return send(200, { outcome: await runMfaResetJob(getSupabaseAdmin(), E2E.tenant, configuredMfaResetProvider(), 'e2e-worker') }); }
      catch (e: any) { return send(409, { code: e?.code ?? 'WORKER_ERROR' }); }
    }
    if (req.method === 'POST' && (m = /^\/rest\/v1\/rpc\/(taxguard_[a-z0-9_]+)$/.exec(path))) {
      const args = json(); if (!args) return send(400, { code: 'PGRST102', message: 'Invalid JSON' });
      const r = await rpc.rpc(m[1], args);
      return r.error ? send(400, { code: r.error.code, message: r.error.message, details: r.error.details, hint: null }) : send(200, r.data);
    }
    if (req.method === 'GET' && (m = /^\/storage\/v1\/bucket\/([a-z0-9_-]+)$/.exec(path)))
      return send(200, { id: m[1], name: m[1], owner: '', public: false, created_at: new Date().toISOString(), updated_at: new Date().toISOString() });
    if (req.method === 'POST' && (m = /^\/storage\/v1\/object\/sign\/([a-z0-9_-]+)\/(.+)$/.exec(path))) {
      if (!objects.has(m[1] + '/' + decodeURIComponent(m[2]))) return send(400, { statusCode: '404', error: 'not_found', message: 'Object not found' });
      return send(200, { signedURL: '/object/sign/' + m[1] + '/' + m[2] + '?token=e2e-synthetic' });
    }
    if (req.method === 'POST' && (m = /^\/storage\/v1\/object\/([a-z0-9_-]+)\/(.+)$/.exec(path))) {
      const id = m[1] + '/' + decodeURIComponent(m[2]);
      if (objects.has(id)) return send(400, { statusCode: '409', error: 'Duplicate', message: 'The resource already exists' });
      objects.set(id, raw);
      return send(200, { Key: id, Id: id });
    }
    if (req.method === 'POST' && path === '/e2e/scan') {
      const b = json() || {};
      const document=(await database.pool.query('SELECT hash FROM taxguard_documents WHERE tenant_id=$1 AND client_id=$2 AND document_id=$3 AND version=$4',[b.tenant,b.client,b.documentId,b.version])).rows[0];
      if(!document)return send(400,{code:'DOCUMENT_NOT_FOUND'});
      const job=await rpc.rpc('taxguard_doc_scan_request',{p_tenant:b.tenant,p_client:b.client,p_document_id:b.documentId,p_version:b.version,p_provider:'e2e-synthetic-scanner',p_ttl_seconds:60});if(job.error)return send(400,{code:job.error.message});
      const r = await rpc.rpc('taxguard_doc_scan_complete', {p_tenant:b.tenant,p_scan_id:job.data.scanId,p_provider:'e2e-synthetic-scanner',p_verdict:b.result});
      return r.error ? send(400, { code: r.error.message }) : send(200, r.data);
    }
    send(404, { code: 'E2E_NOT_AVAILABLE', message: 'Not served in E2E.' });
  });
});
await new Promise<void>(resolve => shim.listen(0, '127.0.0.1', resolve));

process.env.SUPABASE_URL = 'http://127.0.0.1:' + (shim.address() as AddressInfo).port;
process.env.SUPABASE_SERVICE_ROLE_KEY = serviceKey;
process.env.TAXGUARD_PRACTICE_STORE = 'durable';
process.env.TAXGUARD_LEDGER_STORE = 'durable';
process.env.TAXGUARD_TENANT_ID = E2E.tenant;
// Durable staff identity paths (provider sessions, staff access APIs, MFA reset via the adapter).
process.env.TAXGUARD_STAFF_ACCESS_DEVELOPMENT_ENABLED = 'true';
if (PROVIDER_PROFILE) {
  // The browser signs in through the provider emulation (loopback http is accepted by the browser config).
  process.env.VITE_SUPABASE_URL = process.env.SUPABASE_URL;
  process.env.VITE_SUPABASE_ANON_KEY = anonKey;
  process.env.VITE_TAXGUARD_STAFF_ACCESS_DEVELOPMENT_ENABLED = 'true';
  // Client authenticator enrolment (C2) is exercised only against the provider emulation.
  process.env.VITE_TAXGUARD_CLIENT_MFA_ENABLED = 'true';
}
process.env.TAXGUARD_MFA_RESET_PROVIDER = 'supabase-admin';
if (process.env.E2E_CONTROL_FILE) fs.writeFileSync(process.env.E2E_CONTROL_FILE, JSON.stringify({ origin: process.env.SUPABASE_URL, key: serviceKey }), { mode: 0o600 });

// Enrol the synthetic users in the local identity store, then start the real server.
const { db } = await import('../../src/server/db');
const { hashPassword } = await import('../../src/server/auth');
const { registerTotpSecret } = await import('../../src/server/totp');
for (const u of users) {
  db.users.set(u.id, { id: u.id, email: u.email, name: u.name, role: u.role, tenantId: u.tenantId, clientId: u.clientId, authorizedClientIds: u.authorizedClientIds,
    mfaEnabled: true, status: 'active', isVerified: true, onboardingStatus: 'approved', onboardingStep: 15, createdAt: new Date().toISOString() } as any);
  db.userPasswords.set(u.email.toLowerCase(), hashPassword(u.password));
  registerTotpSecret(u.id, u.totp);
}
// Legacy (in-memory) client bindings for the assigned staff, as an administrator assignment would create.
for (const uid of ['e2e-acct', 'e2e-rev']) db.clientAccountantAssignments.set('e2e-binding-' + uid, { id: 'e2e-binding-' + uid, clientId: E2E.client, clientName: 'Synthetic Client One',
  accountantId: uid, accountantName: uid, assignmentType: uid === 'e2e-rev' ? 'reviewer' : 'primary', status: 'active', accessScope: [], assignedBy: 'e2e-admin', assignedByName: 'Synthetic Administrator',
  assignedAt: new Date(Date.now() - 86400000).toISOString(), effectiveDate: new Date(Date.now() - 86400000).toISOString() } as any);
await import('../../server');

const stop = async () => { shim.close(); await database.stop().catch(() => undefined); process.exit(0); };
process.on('SIGTERM', stop); process.on('SIGINT', stop);
process.on('message', m => { if (m === 'stop') void stop(); });
